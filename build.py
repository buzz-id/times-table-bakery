#!/usr/bin/env python3
"""Build the offline-ready site from src/bakery.html.

src/bakery.html is the page body (the same file that is published on claude.ai).
This script writes:
  index.html  - the full page, using the fonts in fonts/ instead of Google Fonts
  sw.js       - the service worker, with a cache name that changes whenever any
                cached file changes, so devices pick up new versions

Run it after every change to src/bakery.html:  python3 build.py
"""
import hashlib
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent

# Files the service worker saves on the device for offline play.
OFFLINE_FILES = [
    "index.html",
    "manifest.webmanifest",
    "fonts/fredoka.woff2",
    "fonts/nunito.woff2",
    "icons/icon-192.png",
    "icons/icon-512.png",
    "icons/icon-maskable-512.png",
    "icons/apple-touch-icon.png",
]

GOOGLE_FONT_LINES = [
    '<link rel="preconnect" href="https://fonts.googleapis.com">\n',
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n',
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Fredoka:wght@500;600;700&family=Nunito:wght@400;600;700;800&display=swap">\n',
]

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="description" content="Multiplication and division for 6 to 8 year olds, taught with trays of cookies. Daily puzzles, stickers and the Cookie Rush game. Works offline.">
<meta name="theme-color" content="#E9F4F9" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#0E1C26" media="(prefers-color-scheme: dark)">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Bakery">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icons/icon-192.png" type="image/png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<link rel="preload" href="fonts/fredoka.woff2" as="font" type="font/woff2" crossorigin>
<link rel="preload" href="fonts/nunito.woff2" as="font" type="font/woff2" crossorigin>
<style>
:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}
body{margin:0}img{max-width:100%}[hidden]{display:none!important}
@font-face{font-family:"Fredoka";font-style:normal;font-weight:300 700;font-display:swap;src:url("fonts/fredoka.woff2") format("woff2")}
@font-face{font-family:"Nunito";font-style:normal;font-weight:200 1000;font-display:swap;src:url("fonts/nunito.woff2") format("woff2")}
.offline-note{margin:0 auto;max-width:940px;font:700 .85rem/1.4 "Nunito","Segoe UI",system-ui,sans-serif;color:var(--muted,#557083);text-align:center}
</style>
</head>
<body>
"""

# Registers the service worker when the page is served from a website (not file://),
# then tells the grown-up once the game is saved for offline play.
TAIL = """
<script>
(function(){
  if(!('serviceWorker' in navigator) || !/^https?:$/.test(location.protocol)) return;
  addEventListener('load', function(){
    navigator.serviceWorker.register('sw.js').then(function(){
      return navigator.serviceWorker.ready;
    }).then(function(){
      var wrap = document.querySelector('.wrap');
      if(!wrap || document.querySelector('.offline-note')) return;
      var p = document.createElement('p');
      p.className = 'offline-note';
      p.textContent = 'Saved on this device. Times Table Bakery now works without wifi.';
      wrap.appendChild(p);
    }).catch(function(){ /* offline saving is a bonus; the page works without it */ });
  });
})();
</script>
</body>
</html>
"""

SW = """/* Times Table Bakery service worker. Generated by build.py; edit build.py, not this file. */
const CACHE = 'ttb-%(version)s';
const FILES = %(files)s;

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE).then(cache => cache.addAll(['./', ...FILES])).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k.startsWith('ttb-') && k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

/* Give up on a slow network after this long and use the saved copy. */
const NETWORK_WAIT_MS = 3000;

function withTimeout(promise, ms) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error('timeout')), ms);
    promise.then(v => { clearTimeout(timer); resolve(v); }, e => { clearTimeout(timer); reject(e); });
  });
}

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    /* The page itself: try the network first so updates arrive, fall back to the saved copy. */
    const network = fetch(req).then(res => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put('./', copy)); }
      return res;
    });
    event.waitUntil(network.catch(() => {}));
    event.respondWith(
      withTimeout(network, NETWORK_WAIT_MS).catch(() =>
        caches.match('./').then(hit => hit || caches.match('index.html')).then(hit => hit || network)
      )
    );
    return;
  }

  /* Fonts, icons and the manifest: use the saved copy, fetch only if it is missing. */
  event.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req)));
});
"""


def main():
    src = (ROOT / "src" / "bakery.html").read_text(encoding="utf-8")
    for line in GOOGLE_FONT_LINES:
        if src.count(line) != 1:
            raise SystemExit(f"build.py: expected this line exactly once in src/bakery.html:\n{line}")
        src = src.replace(line, "")
    if "fonts.googleapis.com" in src or "fonts.gstatic.com" in src:
        raise SystemExit("build.py: src/bakery.html still refers to Google Fonts")

    (ROOT / "index.html").write_text(HEAD + src.rstrip("\n") + "\n" + TAIL, encoding="utf-8")

    digest = hashlib.sha256()
    for name in OFFLINE_FILES:
        path = ROOT / name
        if not path.is_file():
            raise SystemExit(f"build.py: missing {name}")
        digest.update(name.encode())
        digest.update(path.read_bytes())
    version = digest.hexdigest()[:12]

    files = "[\n  " + ",\n  ".join(f"'{n}'" for n in OFFLINE_FILES) + "\n]"
    (ROOT / "sw.js").write_text(SW % {"version": version, "files": files}, encoding="utf-8")
    print(f"Built index.html and sw.js (cache ttb-{version})")


if __name__ == "__main__":
    main()
